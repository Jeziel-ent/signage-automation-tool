"""Full Agarpathi evaluation against the designer's own files.
    python tools/agarpathi_eval.py known|unseen [--only 16,27] [--limit N]
known  = production behaviour (the designer board of the same size is available as a template)
unseen = every designer board of the SAME SIZE as the target is hidden from the template library (leave-same-size-out),
         i.e. how a size the designer never made would come out.
Each board is generated by the real CorelEngine (corel_supervisor worker, master kept open between shops), dumped with
PowerClip contents, and compared element by element with the designer's CDR (cached dump) and with her JPEG."""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
os.environ["SIGNAGE_DUMP_CLIPS"] = "1"
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app import agarpathi_template as T  # noqa: E402
from app import corel_supervisor  # noqa: E402
from app.batch_import import parse_shop_lines  # noqa: E402
from tools.agarpathi_elements import CACHE, elements  # noqa: E402
from tools.agarpathi_fidelity import designer_refs, tamil  # noqa: E402
from tools.metrics import load_config, visual_similarity  # noqa: E402
from tools.validate_all import DATASET, _safe  # noqa: E402

OUT = ROOT / "dataset_analysis" / "agarpathi_fidelity"
MASTERS = {"L": ROOT / "data" / "jobs_v2" / "04b13cef8fc3" / "master.cdr",
           "P": ROOT / "data" / "jobs_v2" / "32b3682cd408" / "master.cdr"}
MASTER_NAME = "SRI KANNIYAMMAN NATTU MARUNTHU KADAI"
EXACT = (2.0, 3.0)      # % of the page: centre / size
CLOSE = (5.0, 6.0)


def compare(ours: dict, des: dict) -> dict:
    """Per-element deviations in percent of the page."""
    res = {}
    for k in ("roof", "sugandha", "blackstone", "stick", "composite", "band", "name_en", "name_ta"):
        if k not in des:
            continue
        if k not in ours:
            res[k] = {"missing": True}
            continue
        o, d = ours[k], des[k]
        if k == "name_ta":   # her Tamil spelling differs from ours: compare the right edge, the row and the height
            dx = ((o["x"] + o["w"]) - (d["x"] + d["w"])) * 100
        else:
            dx = (o["cx"] - d["cx"]) * 100
        dy = (o["cy"] - d["cy"]) * 100
        dw, dh = (o["w"] - d["w"]) * 100, (o["h"] - d["h"]) * 100
        if k.startswith("name"):
            dw = 0.0          # text width follows the text itself
        res[k] = {"dx": dx, "dy": dy, "dw": dw, "dh": dh}
    return res


def verdict(cmp: dict, tol) -> tuple[bool, list]:
    bad = []
    for k, e in cmp.items():
        if k == "band":
            continue
        if e.get("missing"):
            bad.append((k, "missing"))
            continue
        if max(abs(e["dx"]), abs(e["dy"])) > tol[0] or max(abs(e["dw"]), abs(e["dh"])) > tol[1]:
            bad.append((k, round(max(abs(e["dx"]), abs(e["dy"]), abs(e["dw"]), abs(e["dh"])), 1)))
    return not bad, bad


def main():
    mode = sys.argv[1]
    only = {int(x) for x in sys.argv[sys.argv.index("--only") + 1].split(",")} if "--only" in sys.argv else None
    limit = int(sys.argv[sys.argv.index("--limit") + 1]) if "--limit" in sys.argv else None
    run = OUT / f"eval_{mode}"
    run.mkdir(parents=True, exist_ok=True)
    refs = designer_refs()
    files = [f for f in sorted((DATASET / "Agarpathi").glob("*.cdr")) if "copy" not in f.stem.lower()]
    jobs, meta = [], []
    for f in files:
        shop = parse_shop_lines(f.stem).shops[0]
        sno = int(f.stem.split(" - ")[0])
        if only and sno not in only:
            continue
        key = next((k for k in refs if k[0] == sno and k[1] == shop.width and k[2] == shop.height), None)
        if key is None:
            print("no designer image for", f.name)
            continue
        mm = 304.8 if shop.unit.lower().startswith("f") else 25.4
        wmm, hmm = shop.width * mm, shop.height * mm
        fam = "L" if wmm / hmm >= 1.25 else "P"
        safe = _safe(f.stem)
        sd = {"name": shop.name, "width": wmm, "height": hmm, "unit": "mm", "brand": "agarpathi",
              "master_shop_name": MASTER_NAME, "file_base": f"{sno}_{safe[:60]}"}
        if mode == "unseen":
            sd["template_exclude"] = [t["file"] for t in T.templates()
                                      if abs(t["W"] / wmm - 1) < 0.01 and abs(t["H"] / hmm - 1) < 0.01]
        jobs.append({"master_path": str(MASTERS[fam]), "shop": sd, "out_dir": str(run / "out" / safe),
                     })
        meta.append({"sno": sno, "file": f.name, "name": shop.name, "w": shop.width, "h": shop.height, "unit": shop.unit,
                     "fam": fam, "safe": safe, "ref": str(refs[key][0])})
    order = sorted(range(len(jobs)), key=lambda i: (meta[i]["fam"], meta[i]["sno"]))   # one master at a time
    jobs, meta = [jobs[i] for i in order], [meta[i] for i in order]
    if limit:
        jobs, meta = jobs[:limit], meta[:limit]
    for j, ta in zip(jobs, tamil([m["name"] for m in meta])):
        j["shop"]["shop_name_local"] = ta
    cfg = load_config()
    rows_path = run / "results.json"
    rows = json.loads(rows_path.read_text(encoding="utf-8")) if rows_path.exists() else []
    done = {r["file"] for r in rows if r.get("status") == "done"}
    rows = [r for r in rows if r["file"] in done]
    todo = [(j, m) for j, m in zip(jobs, meta) if m["file"] not in done]
    print(f"{mode}: {len(todo)} boards to run ({len(done)} already done)", flush=True)
    chunks = [todo[k:k + 5] for k in range(0, len(todo), 5)]
    for pass_no in (1, 2):
        if pass_no == 2:   # a batch member that failed on a reused CorelDRAW is retried alone in a fresh one (as the app does)
            failed = [(j, m) for j, m in todo if m["file"] in {r["file"] for r in rows if r["status"] != "done"}]
            rows[:] = [r for r in rows if r["status"] == "done"]
            chunks = [[x] for x in failed]
            print(f"retrying {len(failed)} failed boards alone", flush=True)
        _run_chunks(chunks, rows, rows_path, run, cfg)
    _dump_and_compare(rows, rows_path, run)


def _run_chunks(chunks, rows, rows_path, run, cfg):
    for chunk in chunks:

        def on_progress(i, entry, chunk=chunk):
            j, m = chunk[i]
            row = dict(m)
            row["status"], row["seconds"], row["error"] = entry.get("status"), entry.get("seconds"), entry.get("error")
            if entry.get("status") == "done":
                res = entry["result"]
                row["warnings"] = res["report"].get("warnings", [])
                row["files"] = res["files"]
                pv = res["files"].get("preview")
                if pv and Path(pv).is_absolute():
                    png = Path(pv)
                elif pv:
                    png = Path(j["out_dir"]) / Path(pv).name
                else:
                    png = None
                row["png"] = str(png) if png else None
                try:
                    if png and png.exists() and png.suffix.lower() == ".png":
                        row["visual"] = visual_similarity(png, m["ref"], cfg)
                except Exception as e:
                    row["visual_error"] = repr(e)
            rows.append(row)
            rows_path.write_text(json.dumps(rows, indent=1, ensure_ascii=False), encoding="utf-8")
            print(f"[{len(rows)}] {m['sno']} {m['name'][:28]} {row['status']} {row.get('seconds')}s "
                  f"visual={row.get('visual', {}).get('combined')}", flush=True)

        try:
            corel_supervisor.run_batch([c[0] for c in chunk], run / "worker_results.json", overall_timeout_s=400,
                                       job_timeout_s=240, on_progress=on_progress)
        except corel_supervisor.RefusedToStart as e:
            print("REFUSED:", e, flush=True)
            break


if __name__ == "__main__":
    main()


def _dump_and_compare(rows, rows_path, run):
    """Phase 2: COM-dump every generated CDR (with PowerClip contents; separate worker batches, so a dump never shares a
    CorelDRAW with a conversion) and compare each with the designer's CDR."""
    todo = [r for r in rows if r.get("status") == "done" and not r.get("geometry")]
    dumps = run / "ours_dumps"
    dumps.mkdir(exist_ok=True)
    jobs = []
    for r in todo:
        cdr = Path(r["files"]["cdr"])
        cdr = cdr if cdr.is_absolute() else Path(run / "out" / r["safe"]) / cdr.name
        r["_dump"] = dumps / f"{r['sno']}_{r['safe'][:50]}.json"
        if not r["_dump"].exists():
            jobs.append({"dump_only": str(cdr), "dump_cache": str(r["_dump"])})
    print(f"dumping {len(jobs)} generated files", flush=True)
    for k in range(0, len(jobs), 5):
        try:
            corel_supervisor.run_batch(jobs[k:k + 5], run / "dump_results.json", overall_timeout_s=400,
                                       on_progress=lambda i, e: print("  dumped", Path(e.get("dump_only", "")).name[:45], e.get("status"), flush=True))
        except corel_supervisor.RefusedToStart as e:
            print("REFUSED:", e, flush=True)
            break
    for r in todo:
        d = r.pop("_dump")
        try:
            r["geometry"] = compare(elements(json.load(open(d, encoding="utf-8"))),
                                    elements(json.load(open(CACHE / f"{r['safe']}.json", encoding="utf-8"))))
        except Exception as e:
            r["geometry_error"] = repr(e)
    rows_path.write_text(json.dumps(rows, indent=1, ensure_ascii=False), encoding="utf-8")
